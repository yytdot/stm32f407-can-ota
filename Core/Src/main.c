/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  /* 向量表重定向到 App 区（0x08020000）。
   * 必须在 HAL_Init() 之前——HAL 初始化过程中可能就有中断进来，
   * 晚了就会跳到 Bootloader 的向量表里去。 */
  app_set_vector_table();

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_CAN1_Init();
  MX_CRC_Init();
  MX_I2C1_Init();
  MX_IWDG_Init();
  MX_SPI1_Init();
  MX_UART4_Init();
  /* USER CODE BEGIN 2 */

  /* ---- 1. 驱动层初始化 ----
   * 外设本体（时钟、GPIO 复用、位时序）已经在上面 MX_xxx_Init() 里配好了，
   * 这里只做各模块自己的"业务初始化"：传感器指令、CAN 过滤器、Flash 校验等。 */
  w25q64_init();          /* SPI Flash：后续 OTA 升级要用它缓存固件 */
  i2c_sensors_init();     /* SHT30 + BH1750 上电配置 */
  ssd1306_init();         /* OLED 初始化（和传感器共用 I2C1） */
  adc_voltage_init();     /* ADC 电压采集（PA0） */
  can_app_init();         /* CAN 过滤器 + 启动 + 接收队列 + 中断 */
  led_init();             /* PC0/PC1 指示灯 */
  key_init();             /* PC2 按键 */

  /* ---- 2. 创建两个传感器数据队列 ---- */
  s_sensor_queue_oled = xQueueCreate(SENSOR_QUEUE_LENGTH, sizeof(sensor_data_t));
  s_sensor_queue_can  = xQueueCreate(SENSOR_QUEUE_LENGTH, sizeof(sensor_data_t));

  if (s_sensor_queue_oled == NULL || s_sensor_queue_can == NULL) {
      /* 堆不够：先把 LED 拉亮提示，然后停在这里 */
      LED_RUN_ON();
      while (1) {
      }
  }

  /* ---- 3. 创建任务 ----
   * 优先级：task_can(3) > task_sensor/task_oled(1) > task_key_led(0)
   * 两个采集任务各自持有自己的队列，互不干扰。 */
  task_sensor_create(s_sensor_queue_oled);
  task_sensor_create(s_sensor_queue_can);
  task_oled_create(s_sensor_queue_oled);
  task_can_create(s_sensor_queue_can);
  task_key_led_create();

  /* ---- 4. 启动调度器，正常情况下永不返回 ---- */
  vTaskStartScheduler();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

